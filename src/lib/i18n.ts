type Translations = typeof translations;
type TranslationKeys = Translations['ko'];

let currentLanguage: Language = 'ko';

export function setLanguage(lang: Language): void {
  currentLanguage = lang;
}

export function getLanguage(): Language {
  return currentLanguage;
}

export function t<
  K1 extends keyof TranslationKeys,
  K2 extends keyof TranslationKeys[K1],
>(category: K1, key: K2): string {
  const lang = translations[currentLanguage] as TranslationKeys;
  const fallback = translations.ko as TranslationKeys;
  return ((lang[category] as Record<string, string>)[key as string] ||
    (fallback[category] as Record<string, string>)[key as string]) as string;
}

export function tWithParams(
  category: keyof TranslationKeys,
  key: string,
  params: Record<string, string | number>
): string {
  let text = t(category, key as never);
  for (const [k, v] of Object.entries(params)) {
    text = text.replace(`{${k}}`, String(v));
  }
  return text;
}

export function getCategoryLabel(category: string): string {
  const key = category as keyof TranslationKeys['categories'];
  return t('categories', key) || category;
}

export function getLanguageForAI(): string {
  const map: Record<string, string> = { ko: 'Korean', en: 'English', ja: 'Japanese', zh: 'Chinese' };
  return map[currentLanguage] || 'Korean';
}

export function getLanguageCode(): string {
  return currentLanguage;
}

